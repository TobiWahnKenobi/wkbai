// FSR 3.1's upscaler on Diligent (see DiligentFsr3.h). Each frame, as fsr3upscalerDispatch in the
// SDK's ffx_fsr3upscaler.cpp:
//  1. prepare inputs: the depth and motion vectors dilated (the nearest of the 3 x 3 around), the
//     previous frame's depth reconstructed from them, the luma, the farthest depth;
//  2. the luma pyramid (AMD's single-pass downsampler), which also tracks the scene's exposure;
//  3. the shading change pyramid and 4. the shading change: where the lighting changed;
//  5. the reactivity: disocclusions, reactive pixels, new locks on thin features;
//  6. the luma instability;
//  7. the accumulation: the history reprojected through the motion vectors and blended with the
//     current frame, upsampled with a Lanczos kernel, into the output's size;
//  8. RCAS sharpening into the output.
// The internal textures ping-pong between frames as the SDK's. The shaders are the SDK's,
// compiled by Diligent (FXC on D3D12, SM 5: no 16-bit maths or wave operations).

#include "DiligentFsr3.h"
#include "../util/util.h"
#include "ShaderSourceFactoryUtils.h"
